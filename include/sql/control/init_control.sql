Use database RETAIL_DW;


use schema RETAIL_DW.RETAIL_SCHEMA;


USE ROLE SYSADMIN;

CREATE TABLE IF NOT EXISTS RETAIL_DW.RETAIL_SCHEMA.C_BATCH_SCRIPTS (
    script_name     VARCHAR PRIMARY KEY,
    layer           VARCHAR,    -- STG / TMP / TGT
    execution_order INT
);


CREATE TABLE IF NOT EXISTS RETAIL_DW.RETAIL_SCHEMA.C_PARAM (
    run_id          VARCHAR,
    param_name      VARCHAR,
    param_value     VARCHAR,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.RETAIL_SCHEMA.C_BATCH_LOG (
    log_id          NUMBER AUTOINCREMENT,
    run_id          VARCHAR,
    _batch_date      DATE,
    script_name     VARCHAR,
    status          VARCHAR,    -- RUNNING / SUCCESS / FAILED
    start_time      TIMESTAMP,
    end_time        TIMESTAMP,
    rows_read       NUMBER,
    rows_inserted   NUMBER,
    rows_rejected   NUMBER,
    error_message   VARCHAR
);


CREATE TABLE IF NOT EXISTS C_REJ_TABLE (
    _batch_date      DATE,
    source_table    VARCHAR,
    rule_rejected   VARCHAR,    -- NULL_FK, NEG_QTY
    payload         VARIANT,    
    _rejected_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS C_LOAD_DATES (
    target_table    VARCHAR PRIMARY KEY,
    last_load_date  DATE,
    last_run_id     VARCHAR,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);


GRANT OWNERSHIP ON TABLE RETAIL_DW.RETAIL_SCHEMA.C_BATCH_SCRIPTS TO ROLE SYSADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TABLE RETAIL_DW.RETAIL_SCHEMA.C_PARAM         TO ROLE SYSADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TABLE RETAIL_DW.RETAIL_SCHEMA.C_BATCH_LOG     TO ROLE SYSADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TABLE RETAIL_DW.RETAIL_SCHEMA.C_REJ_TABLE     TO ROLE SYSADMIN COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE RETAIL_DW.RETAIL_SCHEMA.C_LOAD_DATES    TO ROLE SYSADMIN COPY CURRENT GRANTS;